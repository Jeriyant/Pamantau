  let lang = 'id';

  function normalizeLang(value) {
    return String(value || '').toLowerCase().trim() === 'en' ? 'en' : 'id';
  }

  function t(key, vars) {
    const table = DICT[lang] || DICT.id;
    let s = table[key];
    if (s == null) s = DICT.id[key];
    if (s == null) s = key;
    if (vars && typeof vars === 'object') {
      s = String(s).replace(/\{(\w+)\}/g, (_, k) => (
        vars[k] != null ? String(vars[k]) : ''
      ));
    }
    return s;
  }

  function setAttrFromKey(el, attr, dataKey) {
    const key = el.getAttribute(dataKey);
    if (!key) return;
    if (attr === 'aria-label') el.setAttribute('aria-label', t(key));
    else if (attr === 'title') el.title = t(key);
    else if (attr === 'placeholder') el.placeholder = t(key);
  }

  /** Update all static chrome marked with data-i18n*. */
  function applyDom(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      el.textContent = t(key);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      setAttrFromKey(el, 'title', 'data-i18n-title');
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      setAttrFromKey(el, 'aria-label', 'data-i18n-aria');
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      setAttrFromKey(el, 'placeholder', 'data-i18n-placeholder');
    });
  }

  function applyLanguage(next, root) {
    lang = normalizeLang(next);
    document.documentElement.lang = lang;
    applyDom(root);
    return lang;
  }

  window.PamantauI18n = {
    DICT,
    t,
    normalizeLang,
    applyLanguage,
    applyDom,
    getLang: () => lang,
  };
